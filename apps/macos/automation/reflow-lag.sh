#!/usr/bin/env bash
# Reflow lag (ADR 0004, reflow lead): how far a terminal's text trails its
# tile's frame during layout motion, and when the last redraw lands against
# the motion's end. In-process automation on a dev instance: no OS input, the
# window stays in the background.
#
#   apps/macos/automation/reflow-lag.sh [LEAD_MS…]   (default: 0 100)
#
# Three terminals run winch-log.py (logs each SIGWINCH, redraws at once).
# For each lead (`anim reflow-lead`): sidebar toggles, divider moves and
# rotates, 700 ms apart, then `anim stats lag-<lead>`; reflow-lag.py matches
# the app's resizes with the panes' SIGWINCHes. Leads alternate over two
# rounds so a busy machine weighs on each the same.
# Output: .dev/<name>-results/lag/. Uses AZJ_DEV_NAME=lag (herdr session
# azj-dev-lag) and resets it.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../../.." && pwd)"
export AZJ_DEV_NAME="${AZJ_DEV_NAME:-lag}"
leads=("${@:-0 100}")
read -r -a leads <<<"${leads[*]}"
out="$root/.dev/$AZJ_DEV_NAME-results/lag"
script="$out.azs"

"$root/apps/macos/dev.sh" --reset >/dev/null 2>&1 || true
rm -f "$root/.dev/$AZJ_DEV_NAME/config/azulejo/config.toml"
rm -rf "$out"
mkdir -p "$out"

emit() { printf '%s\n' "$@" >>"$script"; }
: >"$script"
run_logger="core {\"method\":\"terminal.send_text\",\"params\":{\"text\":\"python3 $here/winch-log.py $out\\n\"}}"
emit "# generated by reflow-lag.sh" "log start" "expect tiles 1" "wait 800" "$run_logger" "wait 800"
emit "key ctrl+cmd+t" "wait 1500" "$run_logger" "wait 800"
emit "key ctrl+cmd+t" "wait 1500" "$run_logger" "wait 1200"
for round in 1 2; do
  for lead in "${leads[@]}"; do
    emit "anim reflow-lead $lead" "anim reset"
    for _ in 1 2 3; do
      emit "key cmd+a" "wait 700" "key cmd+a" "wait 700"
      emit "key ctrl+alt+shift+l" "wait 700" "key ctrl+alt+shift+h" "wait 700"
      emit "key alt+o" "wait 700" "key alt+o" "wait 700" "key alt+o" "wait 700" "key alt+o" "wait 700"
    done
    emit "anim stats lag-$lead-$round"
  done
done
emit "quit"

set +e
"$root/apps/macos/dev.sh" --automation "$script" --out "$out"
status=$?
set -e
"$root/apps/macos/dev.sh" --reset >/dev/null 2>&1 || true
ls "$out"/winch-*.log >/dev/null 2>&1 || { echo "no winch logs: did the loggers start?" >&2; exit 1; }
for lead in "${leads[@]}"; do
  for round in 1 2; do
    echo "== lead $lead, round $round"
    python3 "$here/reflow-lag.py" "$out/lag-$lead-$round.json" "$out"
  done
done
exit $status
