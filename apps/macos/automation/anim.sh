#!/usr/bin/env bash
# Layout motion (PLAN 2.1) on a dev instance, in-process: no OS input, the
# window stays in the background.
#
#   apps/macos/automation/anim.sh            # 50+ animations at the configured speed:
#                                            #   frame pacing, one PTY resize per terminal
#                                            #   per motion (reflow: one plus at most
#                                            #   Motion.maxLiveResizes live ones), no
#                                            #   garbage after the stress
#   apps/macos/automation/anim.sh --slow     # slow motion with mid-animation captures,
#                                            #   checked by outside.py (nothing drawn
#                                            #   outside the cards) and for STALE frames
#   Both include the sidebar collapsing to its rail and opening again, and a
#   toggle turned round mid-motion; --slow also hides it ([sidebar] collapsed
#   = "hidden").
#   AZJ_ANIM_STYLE=outline apps/macos/automation/anim.sh   # one style (reflow, crop,
#                                            #   scale, outline) instead of the configured one
#   AZJ_ANIM_THEME=atom-one-light apps/macos/automation/anim.sh --slow   # in a theme
#                                            #   (docs/themes.md) other than the default
#
# Output: .dev/anim-results/<mode>/{automation.log,anim-stats.json,*.png} (outside
# .dev/anim, which --reset wipes). Exit 0 when the
# script passed. Uses AZJ_DEV_NAME=anim (herdr session azj-dev-anim) and resets it.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../../.." && pwd)"
mode="${1:-stress}"
export AZJ_DEV_NAME="${AZJ_DEV_NAME:-anim}"
results="$root/.dev/$AZJ_DEV_NAME-results"
style="${AZJ_ANIM_STYLE:-}"
theme="${AZJ_ANIM_THEME:-}"
out="$results/${mode#--}${style:+-$style}${theme:+-$theme}"
script="$results/anim-${mode#--}${style:+-$style}.azs"
mkdir -p "$(dirname "$script")"

"$root/apps/macos/dev.sh" --reset >/dev/null 2>&1 || true
# A fresh profile config (dev.sh writes it again): the script edits it
# ([sidebar], [appearance]), and a second run mustn't start from those edits.
rm -f "$root/.dev/$AZJ_DEV_NAME/config/azulejo/config.toml"
rm -rf "$out"
mkdir -p "$out"

# Waits: motion (200 ms by default) plus the reveal (≤ 250 ms after it).
settle=520

emit() { printf '%s\n' "$@" >>"$script"; }
: >"$script"
emit "# generated by anim.sh ($mode)" "log start" "expect tiles 1"
if [[ -n "${AZJ_ANIM_THEME:-}" ]]; then
  emit "sh python3 $here/themes/set-appearance.py {config} theme=$AZJ_ANIM_THEME" \
    "until theme $AZJ_ANIM_THEME 8000" "wait 500"
fi
[[ -n "$style" ]] && emit "anim style $style"

if [[ "$mode" == "--slow" ]]; then
  # 1.5 s motions; captures land mid-way. Keys go through the real router.
  emit "anim duration 1500"
  emit "key ctrl+cmd+t" "wait 2500"            # first split, no capture (herdr binds)
  emit 'core {"method":"terminal.send_text","params":{"text":"vim -c \"set nu\" /etc/hosts\n"}}'
  emit "wait 1500" "capture 00-before 0" "wait 300"
  step() { # name chord
    emit "key $2" "capture $1-a-mid 450" "capture $1-b-mid 900" "wait 1800" "capture $1-c-end 0" "wait 400"
  }
  step 01-split ctrl+cmd+t
  step 02-resize ctrl+alt+shift+h
  step 03-swap alt+shift+h                     # the focused tile sits on the right
  step 04-zoom alt+shift+m
  step 05-unzoom alt+shift+m
  step 06-rotate alt+o                         # Bismuth rotate: master left -> top
  step 06e-rotate-right alt+o                  # -> right
  step 06f-rotate-bottom alt+o                 # -> bottom
  step 06g-rotate-left alt+o                   # -> left again
  # A rotate turned round mid-motion: four quarter turns 500 ms apart, so
  # each one retargets the last from where the tiles show.
  emit "key alt+o" "wait 500" "key alt+o" "capture 06h-rotate-retarget-a-mid 250" "wait 250" \
    "key alt+o" "capture 06h-rotate-retarget-b-mid 250" "wait 250" "key alt+o" \
    "capture 06h-rotate-retarget-c-mid 400" "wait 1800" "capture 06h-rotate-retarget-d-end 0" "wait 400"
  emit "expect orientation left"
  # A manual tab (every adopted herdr tab is one): alt+o turns the whole
  # split tree, and the tiles move to their turned places like Tile's.
  emit "key alt+shift+t" "wait 2500" "expect kind manual"
  step 06i-manual-rotate-top alt+o
  step 06j-manual-rotate-right alt+o
  step 06k-manual-rotate-bottom alt+o
  step 06l-manual-rotate-left alt+o
  emit "expect kind manual" "key alt+shift+t" "wait 2500" "expect kind tile"
  step 06b-masters alt+equal                   # dynamic layouts (ADR 0010)
  step 06b2-masters-back alt+minus
  step 06c-monocle-in alt+z                    # tile -> monocle: focused grows, others tuck away
  emit "expect kind monocle"
  step 06c2-monocle-focus alt+j                # stacked tiles: a quick dissolve, no resize
  step 06c3-monocle-out alt+z                  # monocle -> tile: the others grow back in
  emit "expect kind tile"
  step 06d-three-column alt+bracketleft        # tile -> three column (previous in the cycle)
  emit "expect kind three_column"
  step 06d2-tile alt+bracketright              # three column -> tile (next, wrapping round)
  emit "expect kind tile"
  step 07-focus alt+k                          # the dim cross-fades
  # The sidebar (cmd+a in a terminal): the card turns into the rail and
  # back (its top and right edges move, the rows cross-fade) while the tile
  # area grows and shrinks with it; then a toggle that turns round
  # mid-motion (collapse, and open again 500 ms in).
  step 07b-sidebar-rail cmd+a
  emit "expect sidebar rail"
  step 07c-sidebar-open cmd+a
  emit "expect sidebar visible"
  emit "key cmd+a" "wait 500" "key cmd+a" "capture 07d-sidebar-double-a-mid 300" \
    "capture 07d-sidebar-double-b-mid 900" "wait 1800" "capture 07d-sidebar-double-c-end 0" "wait 400"
  emit "expect sidebar visible"
  # [sidebar] collapsed = "hidden": the card slides out and back instead.
  emit "sh printf '\\n[sidebar]\\ncollapsed = \"hidden\"\\n' >> {config}" "wait 1500"
  step 07e-sidebar-hide cmd+a
  emit "expect sidebar hidden"
  step 07f-sidebar-show cmd+a
  emit "expect sidebar visible"
  step 08-close alt+w
  emit "wait 1200" "anim stats slow-stats"
else
  # Four terminals in the tall layout; vim full-screen in the master.
  emit "key ctrl+cmd+t" "wait 1500"
  emit 'core {"method":"terminal.send_text","params":{"text":"vim -c \"set nu\" /etc/hosts\n"}}'
  emit "wait 800" "key alt+h" "wait $settle"
  emit 'core {"method":"terminal.send_text","params":{"text":"top -s 1 -n 20\n"}}'
  emit "key ctrl+cmd+t" "wait 1200" "key ctrl+cmd+t" "wait 1500"
  emit "anim reset"
  n=0
  cycle=(
    "ctrl+alt+shift+l" "ctrl+alt+shift+h"   # resize: divider right, then back
    "alt+h" "alt+shift+l" "alt+shift+h"     # from the master: swap into the stack and back
    "alt+shift+m" "alt+shift+m"             # zoom, unzoom
    "alt+o" "alt+o" "alt+o" "alt+o"         # rotate: a full clockwise turn
    "alt+enter"                             # promote
    "alt+l" "alt+j" "alt+h"                 # focus moves (ring only)
    "alt+shift+e"                           # equalize
  )
  while ((n < 62)); do
    for chord in "${cycle[@]}"; do
      emit "key $chord" "wait $settle"
      n=$((n + 1))
    done
  done
  # Dynamic layouts (ADR 0010): round the cycle through every kind and
  # back, masters and the master area up and down, Monocle in, a focus
  # switch in it (no PTY resize) and out, manual and back, a move along
  # the order, rotate part, promote.
  layouts=(
    "alt+bracketright" "alt+bracketright" "alt+bracketright"   # tile -> monocle -> three column -> tile
    "alt+bracketleft" "alt+bracketleft" "alt+bracketleft"      # and back
    "alt+equal" "alt+minus"                                   # masters 2, then 1
    "alt+shift+equal" "alt+shift+minus"                       # master area bigger, smaller
    "alt+z" "alt+j" "alt+k" "alt+z"                           # monocle in, focus x2, out
    "alt+t" "alt+t"                                           # tile toggles to the previous kind and back
    "alt+shift+t" "alt+shift+t"                               # manual and back
    "alt+shift+bracketright" "alt+shift+bracketleft"          # move along the order and back
    "alt+shift+o" "alt+shift+o"                               # rotate part and back
  )
  for _ in 1 2; do
    for chord in "${layouts[@]}"; do
      emit "key $chord" "wait $settle"
    done
  done
  emit "expect kind tile" "expect orientation left"
  # Rapid repeats: each key lands 150 ms into the last one's motion (a
  # retarget from where the tiles show). A full turn, the cycle through
  # every kind, Monocle in and straight out, masters up and down.
  emit "key alt+o" "key alt+o" "key alt+o" "key alt+o" "wait $settle"
  emit "expect orientation left"
  emit "key alt+bracketright" "key alt+bracketright" "key alt+bracketright" "wait $settle"
  emit "expect kind tile"
  emit "key alt+z" "key alt+z" "wait $settle" "expect kind tile"
  emit "key alt+equal" "key alt+minus" "wait $settle"
  emit "key alt+bracketleft" "key alt+bracketleft" "key alt+bracketright" "key alt+bracketright" "wait $settle"
  emit "expect kind tile"
  # The sidebar collapses to its rail and opens, four times (every terminal
  # resizes once each way), then collapses and opens again 150 ms apart
  # (each step waits 150 ms): the second toggle turns the first round
  # mid-motion (a retarget), so each terminal resizes twice in one chain.
  for _ in 1 2 3 4; do
    emit "key cmd+a" "wait $settle" "expect sidebar rail" "key cmd+a" "wait $settle" "expect sidebar visible"
  done
  emit "key cmd+a" "key cmd+a" "wait $settle" "expect sidebar visible"
  # Close and split again (a terminal fades out, a new one grows in).
  emit "key alt+w" "wait 1000" "key ctrl+cmd+t" "wait 1500"
  # Tab switch: a new tab, then back (cross-fade).
  emit "key cmd+shift+t" "wait 1200" "key ctrl+1" "wait 600"
  # Main-thread ticks: allow 3 single missed ticks in ~1,250 (other work on a
  # busy machine); resizes must match exactly.
  emit "wait 800" "anim stats" "anim expect-clean 3"
  emit "capture 90-after-stress 0" "wait 1200" "shot 91-after-stress"
  # Off: changes are instant.
  emit "anim enabled false" "anim reset" "key alt+shift+m" "wait 50" "capture 92-off-zoom 0"
  emit "wait 1200" "key alt+shift+m" "wait 300" "anim stats off-stats"
fi
emit "quit"

# The app asks for window captures by dropping files in $out/.capture (it has
# no Screen Recording permission of its own); take them from here.
watch_captures() {
  mkdir -p "$out/.capture"
  while [[ ! -f "$out/result" ]]; do
    for req in "$out/.capture"/*; do
      [[ -e "$req" ]] || continue
      name="$(basename "$req")"
      rm -f "$req"
      wid="$(cat "$out/window-id" 2>/dev/null || true)"
      [[ -n "$wid" ]] && /usr/sbin/screencapture -l "$wid" -x -o "$out/$name.png" 2>/dev/null || true
    done
    sleep 0.01
  done
}
watch_captures &
watcher=$!

set +e
"$root/apps/macos/dev.sh" --automation "$script" --out "$out"
status=$?
set -e
kill "$watcher" 2>/dev/null || true
rm -rf "$out/.capture"
# The system capture needs an unlocked screen; the app's own render
# (<name>-app.png) lands either way.
asked="$(grep -c ' capture ' "$out/automation.log" 2>/dev/null || true)"
taken="$(find "$out" -maxdepth 1 -name '*.png' ! -name '*-app.png' ! -name '*-stress.png' 2>/dev/null | wc -l | tr -d ' ')"
rendered="$(find "$out" -maxdepth 1 -name '*-app.png' 2>/dev/null | wc -l | tr -d ' ')"
if [[ "${asked:-0}" -gt 0 ]]; then
  echo "captures: $asked asked, $taken system (screencapture), $rendered in-app"
  [[ "$taken" -lt "$asked" ]] && echo "  (system captures missing: is the screen locked? the -app.png renders cover the motion)"
fi
stale="$(grep -c '  STALE ' "$out/automation.log" 2>/dev/null || true)"
[[ "${stale:-0}" -gt 0 ]] && echo "stale terminal frames in captures: $stale (STALE lines in automation.log)"
if [[ "$mode" == "--slow" ]]; then
  # Mid-motion captures: nothing drawn outside the cards (tiles and the
  # sidebar card where they show at that instant), and no stale frames.
  if python3 "$here/outside.py" "$out" >"$out/outside.txt"; then
    tail -n 1 "$out/outside.txt"
  else
    tail -n 1 "$out/outside.txt"
    grep -v ' outside-bright=0 ' "$out/outside.txt" | sed 's/^/  /'
    status=1
  fi
  [[ "${stale:-0}" -gt 0 ]] && status=1
fi
true
"$root/apps/macos/dev.sh" --reset >/dev/null 2>&1 || true
echo "stats: $out/anim-stats.json"
exit $status
